"""Generate bundled strings from the reviewed, five-column translation table.

This is a resource generator, not an application build or a runtime test.
Column order: English key, Simplified Chinese, Spanish, French, Japanese.
Keep user content and persisted category/route identifiers out of this table.
"""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "design/localization/interface-translations.tsv"
LANGUAGES = ("en", "zh-Hans", "es", "fr", "ja")
entries = {}
for line_number, line in enumerate(SOURCE.read_text().splitlines(), 1):
    if not line:
        continue
    columns = [value.replace(r"\n", "\n") for value in line.split("\t")]
    if len(columns) != len(LANGUAGES) or any(not column for column in columns):
        raise ValueError(f"Line {line_number}: expected five nonempty columns")
    key = columns[0]
    if key in entries:
        raise ValueError(f"Line {line_number}: duplicate key {key!r}")
    tokens = re.findall(r"%(?:\d+\$)?(?:lld|ld|d|@|f)", key)
    for translation in columns[1:]:
        if re.findall(r"%(?:\d+\$)?(?:lld|ld|d|@|f)", translation) != tokens:
            raise ValueError(f"Line {line_number}: format arguments do not match")
    entries[key] = columns

for column, language in enumerate(LANGUAGES):
    folder = ROOT / "Koko/Resources" / f"{language}.lproj"
    folder.mkdir(parents=True, exist_ok=True)
    content = "// Generated by scripts/generate_interface_localizations.py.\n"
    for key, translations in sorted(entries.items()):
        content += f"{json.dumps(key, ensure_ascii=False)} = {json.dumps(translations[column], ensure_ascii=False)};\n"
    (folder / "Localizable.strings").write_text(content)
print(f"Generated {len(entries)} translated entries in each of {len(LANGUAGES)} languages.")
